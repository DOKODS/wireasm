//! WireASM code generation: a node graph becomes target assembler.

mod aarch64;
mod arduino;
mod avr;
mod c_lang;
mod stm32;
mod x86_64;

use crate::model::*;
use crate::validate::{validate, Diagnostic, Severity};
use std::collections::BTreeMap;

pub const VERSION: &str = "0.4.0";

#[derive(Clone, Debug, Default)]
pub struct CompileStats {
    pub nodes: usize,
    pub edges: usize,
    pub lines: usize,
    pub labels: usize,
}

#[derive(Clone, Debug)]
pub struct CompileOutput {
    pub ok: bool,
    pub asm: String,
    pub diagnostics: Vec<Diagnostic>,
    pub stats: CompileStats,
}

pub fn compile(g: &Graph) -> CompileOutput {
    let diagnostics = validate(g);
    let ok = !diagnostics.iter().any(|d| d.severity == Severity::Error);
    let stats = CompileStats {
        nodes: g.nodes.len(),
        edges: g.edges.len(),
        ..Default::default()
    };

    if !ok {
        let mut asm = String::new();
        asm.push_str(&header(g));
        asm.push_str("\n// Compilation stopped: the graph has errors.\n");
        for d in diagnostics.iter().filter(|d| d.severity == Severity::Error) {
            asm.push_str(&format!("// ERROR: {}\n", d.message));
        }
        return CompileOutput {
            ok,
            asm,
            diagnostics,
            stats,
        };
    }

    let target = Target::parse(&g.target).unwrap();
    let mut diagnostics = diagnostics;
    let generated = if target.is_avr() {
        avr::generate(g, target, &mut diagnostics)
    } else if target.is_stm32() {
        stm32::generate(g, target, &mut diagnostics)
    } else if target.is_esp() {
        arduino::generate(g, target, &mut diagnostics)
    } else if target.is_source() {
        c_lang::generate(g, target, &mut diagnostics)
    } else if target.is_aarch64() {
        aarch64::generate(g, target, &mut diagnostics)
    } else {
        x86_64::generate(g, target, &mut diagnostics)
    };

    match generated {
        Ok(mut asm) => {
            let lines = asm.lines().count();
            let labels = asm
                .lines()
                .filter(|l| {
                    let t = l.trim();
                    t.ends_with(':') && !t.starts_with('.')
                })
                .count();
            let comment = comment_prefix(target);
            asm.push_str(&format!(
                "\n{comment} end of {} — {} lines, {} labels\n",
                target.as_str(),
                lines,
                labels
            ));
            CompileOutput {
                ok: !diagnostics.iter().any(|d| d.severity == Severity::Error),
                asm,
                stats: CompileStats {
                    lines,
                    labels,
                    ..stats
                },
                diagnostics,
            }
        }
        Err(e) => {
            diagnostics.push(Diagnostic::error(None, format!("codegen failed: {e}")));
            CompileOutput {
                ok: false,
                asm: format!("{}\n// codegen failed: {e}\n", header(g)),
                diagnostics,
                stats,
            }
        }
    }
}

fn header(g: &Graph) -> String {
    let t = Target::parse(&g.target);
    let c = t.map(comment_prefix).unwrap_or("//");
    let rule = format!("{c} ============================================================");
    let mut s = String::new();
    s.push_str(&format!(
        "{rule}\n{c} WireASM {} — generated {}\n{c} graph: {}\n{c} target: {}\n{c} entry: {}\n{c} nodes: {}, edges: {}\n{c} Do not edit this file by hand: edit the graph and recompile.\n{rule}\n",
        VERSION,
        t.map(|t| if t.is_asm() { "assembler" } else { "source" })
            .unwrap_or("output"),
        g.name,
        g.target,
        t.map(|t| t.entry_symbol()).unwrap_or("?"),
        g.nodes.len(),
        g.edges.len()
    ));
    s
}

/// Comment prefix for the generated file.
pub fn comment_prefix(t: Target) -> &'static str {
    if t.is_avr() {
        ";"
    } else if t.is_stm32() {
        "@"
    } else {
        "//"
    }
}

pub struct Emitter {
    pub lines: Vec<String>,
    pub comment_prefix: &'static str,
}

impl Default for Emitter {
    fn default() -> Self {
        Self::new()
    }
}

impl Emitter {
    pub fn new() -> Self {
        Emitter {
            lines: Vec::new(),
            comment_prefix: "//",
        }
    }

    pub fn with_comment(prefix: &'static str) -> Self {
        Emitter {
            lines: Vec::new(),
            comment_prefix: prefix,
        }
    }

    pub fn push(&mut self, line: impl AsRef<str>) {
        self.lines.push(line.as_ref().to_string());
    }

    pub fn ins(&mut self, line: impl AsRef<str>) {
        self.lines.push(format!("\t{}", line.as_ref()));
    }

    pub fn label(&mut self, label: &str) {
        self.lines.push(format!("{label}:"));
    }

    pub fn comment(&mut self, text: impl AsRef<str>) {
        for line in text.as_ref().lines() {
            self.lines.push(format!("{} {line}", self.comment_prefix));
        }
    }

    pub fn blank(&mut self) {
        self.lines.push(String::new());
    }

    pub fn finish(self) -> String {
        let mut s = self.lines.join("\n");
        s.push('\n');
        s
    }
}

#[derive(Clone, Debug)]
pub struct Layout {
    pub var_off: BTreeMap<String, usize>,
    pub temp_base: usize,
    pub arg_base: usize,
    pub callret: usize,
    pub rawret: usize,
    pub custom_slots: BTreeMap<String, usize>,
    pub custom_temp_base: usize,
    pub frame: usize,
}

impl Layout {
    pub fn new(g: &Graph) -> Self {
        let mut var_off = BTreeMap::new();
        for (i, name) in g.all_variable_names().into_iter().enumerate() {
            var_off.insert(name, 8 + i * 8);
        }
        let nvars = var_off.len();
        let temp_base = nvars;
        let arg_base = nvars + 128;
        let callret = arg_base + 8;
        let rawret = callret + 1;
        let mut slot = rawret + 1;
        let mut custom_slots = BTreeMap::new();
        for n in &g.nodes {
            if let Some(def) = g.custom(&n.kind) {
                if def.u64_output().is_some() {
                    custom_slots.insert(n.id.clone(), 8 + slot * 8);
                    slot += 1;
                }
            }
        }
        let custom_temp_base = slot;
        let total = (custom_temp_base + 64 * 8 + 1) * 8;
        let frame = (total + 15) & !15;
        Layout {
            var_off,
            temp_base,
            arg_base,
            callret,
            rawret,
            custom_slots,
            custom_temp_base,
            frame,
        }
    }

    pub fn var(&self, name: &str) -> Option<usize> {
        self.var_off.get(name).copied()
    }

    pub fn temp(&self, depth: usize) -> usize {
        8 + (self.temp_base + depth) * 8
    }

    pub fn arg(&self, i: usize) -> usize {
        8 + (self.arg_base + i) * 8
    }

    pub fn callret(&self) -> usize {
        8 + self.callret * 8
    }

    pub fn rawret(&self) -> usize {
        8 + self.rawret * 8
    }

    pub fn custom_slot(&self, node_id: &str) -> Option<usize> {
        self.custom_slots.get(node_id).copied()
    }

    /// Dedicated slots for the inputs of an inlined custom data node. Eight
    /// slots per expression depth, so nested custom nodes cannot clobber the
    /// already evaluated inputs.
    pub fn custom_temp(&self, depth: usize, i: usize) -> usize {
        8 + (self.custom_temp_base + depth * 8 + i) * 8
    }
}

#[derive(Clone, Debug)]
pub struct StringLit {
    pub label: String,
    pub bytes: Vec<u8>,
}

/// Collect PrintStr payloads into a string table, mapping node id -> label.
pub fn collect_strings(g: &Graph) -> (Vec<StringLit>, BTreeMap<String, String>) {
    let mut lits = Vec::new();
    let mut map = BTreeMap::new();
    for n in &g.nodes {
        if n.kind == "PrintStr" || n.kind == "McuUartWriteStr" {
            let text = n.prop("text");
            let label = format!("Lstr{}", lits.len());
            lits.push(StringLit {
                label: label.clone(),
                bytes: text.as_bytes().to_vec(),
            });
            map.insert(n.id.clone(), label);
        }
    }
    (lits, map)
}

pub fn uses_print_u64(g: &Graph) -> bool {
    g.nodes
        .iter()
        .any(|n| n.kind == "PrintU64" || (n.kind == "Call" && n.prop("func").trim() == "print_u64"))
}

pub fn sanitize(id: &str) -> String {
    let mut s = String::from("L");
    for c in id.chars() {
        if c.is_ascii_alphanumeric() || c == '_' {
            s.push(c);
        } else {
            s.push('_');
        }
    }
    s
}

pub fn c_symbol(func: &str, t: Target) -> String {
    if t.is_macos() && !func.starts_with('_') && func != "print_u64" {
        format!("_{func}")
    } else {
        func.to_string()
    }
}

pub fn data_section(t: Target) -> &'static str {
    if t.is_macos() {
        ".section __TEXT,__cstring,cstring_literals"
    } else {
        ".section .rodata"
    }
}

pub fn emit_bytes(em: &mut Emitter, label: &str, bytes: &[u8]) {
    em.label(label);
    let mut all: Vec<u8> = bytes.to_vec();
    all.push(0);
    for chunk in all.chunks(20) {
        let body = chunk
            .iter()
            .map(|b| b.to_string())
            .collect::<Vec<_>>()
            .join(",");
        em.ins(format!(".byte {body}"));
    }
}

/// Emit assembler text from a `RawAsm` or custom node. Lines starting with
/// `.` or ending with `:` are emitted without indentation; the rest get a tab.
pub fn emit_snippet(em: &mut Emitter, text: &str) {
    for line in text.lines() {
        let t = line.trim_end();
        if t.trim().is_empty() {
            continue;
        }
        if t.trim_start().starts_with('.') || t.trim_end().ends_with(':') {
            em.push(t);
        } else {
            em.ins(t.trim_start());
        }
    }
}

/// Replace custom-node placeholders in an assembler template.
///
/// Supported placeholders:
/// * `{in0}`..`{in7}` — register holding the corresponding u64 input;
/// * `{a}`, `{b}` — aliases for `{in0}`, `{in1}`;
/// * `{out}` — result register (`x0` on AArch64, `rax` on x86-64);
/// * `{label}` — unique label prefix for this inline expansion;
/// * `{prop:key}` — string property `key` of the node.
pub fn expand_custom_template(
    text: &str,
    node: &Node,
    input_regs: &[String],
    out_reg: &str,
    label: &str,
) -> String {
    let mut s = text.replace("{label}", label).replace("{out}", out_reg);
    for (i, reg) in input_regs.iter().enumerate() {
        s = s.replace(&format!("{{in{i}}}"), reg);
    }
    if let Some(reg) = input_regs.first() {
        s = s.replace("{a}", reg);
    }
    if let Some(reg) = input_regs.get(1) {
        s = s.replace("{b}", reg);
    }
    // {prop:key} — values are inserted verbatim; the graph author is trusted.
    while let Some(start) = s.find("{prop:") {
        let Some(rel_end) = s[start + 6..].find('}') else {
            break;
        };
        let end = start + 6 + rel_end;
        let key = s[start + 6..end].to_string();
        let value = node.prop(&key).to_string();
        s.replace_range(start..=end, &value);
    }
    s
}
